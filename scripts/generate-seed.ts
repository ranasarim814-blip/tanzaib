/**
 * Writes supabase/seed.sql from lib/demo (the same data demo mode uses).
 * Run: pnpm seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_SETTINGS } from "../lib/config";
import { buildDemoSeed } from "../lib/demo/seed-data";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function inserts(table: string, rows: Record<string, unknown>[], conflict = "id") {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into ${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do nothing;\n\n`;
}

const seed = buildDemoSeed();
let sql = `-- Generated by scripts/generate-seed.ts — dummy catalogue + 3 sample orders.
-- Safe to re-run (on conflict do nothing). Replace products from the admin panel.
begin;

`;
sql += inserts("categories", seed.categories as never);
sql += inserts("products", seed.products as never);
sql += inserts("product_images", seed.product_images as never);
sql += inserts("product_variants", seed.product_variants as never);
sql += inserts("orders", seed.orders as never);
sql += inserts("order_items", seed.order_items as never);
sql += inserts("order_status_history", seed.order_status_history as never);
sql += `insert into settings (key, value) values\n${Object.entries(DEFAULT_SETTINGS)
  .map(([key, value]) => `  (${lit(key)}, '${JSON.stringify(value).replace(/'/g, "''")}'::jsonb)`)
  .join(",\n")}\non conflict (key) do nothing;\n\n`;
sql += `select setval('order_number_seq', greatest((select count(*) from orders), 1));\n\ncommit;\n`;

writeFileSync(join(process.cwd(), "supabase", "seed.sql"), sql);
console.log("Wrote supabase/seed.sql");
